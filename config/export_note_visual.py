def init_xlsx():
    if os.path.exists(XLSX):
        print("已存在，未覆盖：" + XLSX)
        return
    wb = Workbook()
    doc = wb.active
    doc.title = SHEET_DOC
    doc.column_dimensions["A"].width = 110
    for i, line in enumerate(DOC_LINES, start=1):
        doc.cell(row=i, column=1, value=line)
    doc["A1"].font = Font(size=14, bold=True)

    ws = wb.create_sheet(SHEET_TABLE)
    head_fill = PatternFill("solid", fgColor="1B323B")
    head_font = Font(bold=True, color="E8F6F5")
    for c, name in enumerate(COLUMNS, start=1):
        cell = ws.cell(row=1, column=c, value=name)
        cell.fill = head_fill
        cell.font = head_font
        cell.alignment = Alignment(horizontal="center")
    for r, row in enumerate(DEFAULT_ROWS, start=2):
        for c, v in enumerate(row, start=1):
            ws.cell(row=r, column=c, value=v)
    for col, w in zip("ABCDEFGH", (14, 14, 12, 34, 8, 8, 8, 30)):
        ws.column_dimensions[col].width = w
    ws.freeze_panes = "A2"
    wb.save(XLSX)
    print("WROTE " + XLSX)


def read_rows():
    wb = load_workbook(XLSX, data_only=True)
    if SHEET_TABLE not in wb.sheetnames:
        raise SystemExit("找不到工作表：" + SHEET_TABLE)
    ws = wb[SHEET_TABLE]
    rows, errors = [], []
    for r in range(2, ws.max_row + 1):
        vals = [ws.cell(row=r, column=c).value for c in range(1, len(COLUMNS) + 1)]
        if vals[0] is None or str(vals[0]).strip() == "":
            continue
        note_type = str(vals[0]).strip()
        shape_label = str(vals[1] if vals[1] is not None else "").strip()
        src_label = str(vals[2] if vals[2] is not None else "程序化").strip()
        path = str(vals[3] if vals[3] is not None else "").strip()
        w = float(vals[4] or 0)
        h = float(vals[5] or 0)
        enabled = bool(vals[6]) if vals[6] is not None else True
        if shape_label not in SHAPES:
            errors.append("第%d行 形状「%s」不在可选值内" % (r, shape_label))
            continue
        if src_label not in SOURCES:
            errors.append("第%d行 素材来源「%s」不在可选值内" % (r, src_label))
            continue
        if w <= 0 or h <= 0:
            errors.append("第%d行 宽/高必须为正数" % r)
            continue
        if SOURCES[src_label] == "Sprite" and not path:
            errors.append("第%d行 选了位图素材但没填素材路径" % r)
        rows.append(dict(note_type=note_type, shape=SHAPES[shape_label], source=SOURCES[src_label],
                         path=path, w=w, h=h, enabled=enabled))
    return rows, errors


