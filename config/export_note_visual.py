def export_cs(rows):
    body = []
    for r in rows:
        body.append('                new NoteVisualRow("%s", NoteShapeKind.%s, NoteArtSource.%s, "%s", %gf, %gf, %s),'
                    % (r["note_type"], r["shape"], r["source"], r["path"].replace("\\", "/"),
                       r["w"], r["h"], "true" if r["enabled"] else "false"))
    text = "\n".join(HEAD + body + TAIL) + "\n"
    with open(CS, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("WROTE %s（%d 行）" % (CS, len(rows)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["init", "export", "check"])
    args = ap.parse_args()
    if args.mode == "init":
        init_xlsx()
        return
    if not os.path.exists(XLSX):
        raise SystemExit("找不到源表，先执行 init：" + XLSX)
    rows, errors = read_rows()
    for e in errors:
        print("[错误] " + e)
    if errors:
        sys.exit(1)
    print("源表校验通过：%d 行" % len(rows))
    if args.mode == "check":
        return
    export_cs(rows)


if __name__ == "__main__":
    main()
